/* ── Report building blocks ───────────────────────────────────────────────────
 *
 * Every RISYS report is built from these, so a board pack, an ECC status
 * report and an audit report share one visual language: the ink cover with the
 * cream mark, DM Serif section titles in wine, crimson rules, blush table heads.
 * -------------------------------------------------------------------------- */
import { Document, Page, Image, StyleSheet } from '@react-pdf/renderer'
import { View, Text } from './rtl'
import { C, BAND } from './theme'
import { FONT_SANS, FONT_DISPLAY, reportAssets, FONT_ARABIC } from './assets'
import { tx } from '@/lib/i18n'

const PAD_X = 42
const PAD_TOP = 64
const PAD_BOTTOM = 56

export const s = StyleSheet.create({
  page:      { fontFamily: [FONT_SANS, FONT_ARABIC], fontSize: 8.6, color: C.text, lineHeight: 1.45,
               paddingTop: PAD_TOP, paddingBottom: PAD_BOTTOM, paddingHorizontal: PAD_X, backgroundColor: C.white },
  p:         { marginBottom: 6 },
  muted:     { color: C.text3 },
  text2:     { color: C.text2 },
  bold:      { fontWeight: 600 },
  eyebrow:   { fontSize: 7, fontWeight: 600, color: C.rose, letterSpacing: 1.4, textTransform: 'uppercase', marginBottom: 3 },
  h2:        { fontFamily: FONT_DISPLAY, fontSize: 19, color: C.wine, lineHeight: 1.15 },
  h3:        { fontSize: 10.5, fontWeight: 600, color: C.crimson, marginTop: 12, marginBottom: 5 },
  h4:        { fontSize: 8.6, fontWeight: 600, color: C.rose, marginTop: 8, marginBottom: 3 },
  row:       { flexDirection: 'row' },
})

/* ── Document, cover, content page ────────────────────────────────────────── */

export function ReportDocument({ meta, children }) {
  return (
    <Document title={`${meta.title} — ${meta.orgName}`} author="RISYS" subject={meta.title}
              creator="RISYS" producer="RISYS" keywords={meta.reportId ?? ''}>
      {children}
    </Document>
  )
}

