/* ── Table ────────────────────────────────────────────────────────────────── */

/**
 * columns: [{ key, label, width (flex weight or number), align, render(row) }]
 * A row never splits across pages. `heading` (optional) is kept on the same
 * page as the column header and the first row.
 */
export function Table({ columns, rows, empty = 'None recorded.', dense, indentKey, heading }) {
  const total = columns.reduce((a, c) => a + (c.width ?? 1), 0)
  const cellStyle = (c) => ({
    width: `${((c.width ?? 1) / total) * 100}%`,
    paddingHorizontal: 5,
    paddingVertical: dense ? 3.2 : 4.6,
    textAlign: c.align ?? 'left',
  })
  const header = (
    <View style={[s.row, { backgroundColor: C.surface, borderTopWidth: 0.6, borderTopColor: C.border,
                           borderBottomWidth: 1.2, borderBottomColor: C.crimson }]}>
      {columns.map((c) => (
        <Text key={c.key} style={[cellStyle(c), { fontSize: 6.6, fontWeight: 600, color: C.crimson,
                                                  letterSpacing: 0.7, textTransform: 'uppercase' }]}>
          {c.label}
        </Text>
      ))}
    </View>
  )
  // Rows may split across a page. Unbreakable rows (wrap={false}) made
  // react-pdf squeeze whole tables into a strip at the foot of some pages.
  const row = (r, i) => (
    <View key={i}
          style={[s.row, { flexShrink: 0, backgroundColor: i % 2 ? C.hover : C.white, borderBottomWidth: 0.6,
                           borderBottomColor: C.border3, alignItems: 'flex-start' }]}>
      {columns.map((c, ci) => {
        const v = c.render ? c.render(r) : r[c.key]
        const indent = ci === 0 && indentKey && r[indentKey] ? 10 : 0
        return (
          <View key={c.key} style={[cellStyle(c), { paddingLeft: 5 + indent,
                                                     alignItems: c.align === 'right' ? 'flex-end' : c.align === 'center' ? 'center' : 'flex-start' }]}>
            {v === null || v === undefined || v === ''
              ? <Text style={{ fontSize: dense ? 7.4 : 7.8, color: C.text3 }}>—</Text>
              : (typeof v === 'string' || typeof v === 'number')
                ? <Text style={{ fontSize: dense ? 7.4 : 7.8, color: ci === 0 ? C.text : C.text2,
                                 fontWeight: c.bold ? 600 : 400, textAlign: c.align ?? 'left' }}>{String(v)}</Text>
                : v}
          </View>
        )
      })}
    </View>
  )
  // The headings and the column header carry minPresenceAhead, so they move to
  // the next page rather than sit alone at its foot. (This used to be one wrap={false} group holding the heading,
  // header and first row; react-pdf then squeezed whole tables into a strip
  // at the bottom of the page when that group had to move.)
  return (
    <View style={{ marginBottom: 10 }}>
      {heading}
      <View minPresenceAhead={30}>{header}</View>
      {rows.length === 0 ? (
        <Text style={{ paddingVertical: 8, paddingHorizontal: 5, color: C.text3, borderBottomWidth: 0.6, borderBottomColor: C.border }}>
          {empty}
        </Text>
      ) : rows.map((r, i) => row(r, i))}
    </View>
  )
}

/* ── Charts ───────────────────────────────────────────────────────────────── */

/**
 * Likelihood × impact heat map. cells: { 'l-i': { band, count } }.
 * Likelihood runs 5 → 1 top to bottom, impact 1 → 5 left to right — the
 * orientation the register uses on screen.
 */
export function HeatMap({ title, cells, dims = 5, total, cellSize = 27 }) {
  const rowsL = Array.from({ length: dims }, (_, k) => dims - k)
  const colsI = Array.from({ length: dims }, (_, k) => k + 1)
  return (
    <View wrap={false} style={{ alignItems: 'flex-start' }}>
      <Text style={{ fontSize: 8, fontWeight: 600, color: C.crimson, marginBottom: 5 }}>
        {title}{typeof total === 'number' ? <Text style={{ color: C.text3, fontWeight: 400 }}> · {total} {tx('scored')}</Text> : null}
      </Text>
      <View style={s.row}>
        <View style={{ width: 12, justifyContent: 'center' }}>
          <Text style={{ fontSize: 6, color: C.text3, transform: 'rotate(-90deg)', width: 60, marginLeft: -24 }}>{tx('LIKELIHOOD')}</Text>
        </View>
        <View>
          {rowsL.map((l) => (
            <View key={l} style={s.row}>
              <Text style={{ width: 10, fontSize: 6.2, color: C.text3, textAlign: 'right', paddingRight: 3, paddingTop: cellSize / 2 - 4 }}>{l}</Text>
              {colsI.map((i) => {
                const cell = cells[`${l}-${i}`] ?? {}
                const m = BAND[cell.band] ?? BAND.none
                const n = cell.count ?? 0
                return (
                  <View key={i} style={{ width: cellSize, height: cellSize, margin: 1, backgroundColor: n ? m.color : m.bg,
                                         borderWidth: 0.6, borderColor: m.border, alignItems: 'center', justifyContent: 'center' }}>
                    {n ? <Text style={{ fontSize: 8.5, fontWeight: 700, color: C.white }}>{n}</Text> : null}
                  </View>
                )
              })}
            </View>
          ))}
          <View style={[s.row, { marginLeft: 10 }]}>
            {colsI.map((i) => (
              <Text key={i} style={{ width: cellSize, margin: 1, fontSize: 6.2, color: C.text3, textAlign: 'center' }}>{i}</Text>
            ))}
          </View>
          <Text style={{ fontSize: 6, color: C.text3, textAlign: 'center', marginLeft: 10 }}>{tx('IMPACT')}</Text>
        </View>
      </View>
    </View>
  )
}

