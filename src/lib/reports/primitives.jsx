export function SectionTitle({ eyebrow, title, first, breakBefore }) {
  return (
    <View break={breakBefore} minPresenceAhead={90} style={{ marginTop: first ? 0 : 16, marginBottom: 10 }}>
      {eyebrow ? <Text style={s.eyebrow}>{eyebrow}</Text> : null}
      <Text style={s.h2}>{title}</Text>
      <View style={[s.row, { marginTop: 7 }]}>
        <View style={{ width: 34, height: 2, backgroundColor: C.crimson }} />
        <View style={{ flex: 1, height: 0.6, backgroundColor: C.border, marginTop: 0.7 }} />
      </View>
    </View>
  )
}

export const H3 = ({ children }) => <Text minPresenceAhead={40} style={s.h3}>{children}</Text>
export const H4 = ({ children }) => <Text minPresenceAhead={30} style={s.h4}>{children}</Text>
export const P = ({ children, style }) => <Text style={[s.p, style]}>{children}</Text>
export const Muted = ({ children, style }) => <Text style={[s.p, s.muted, { fontSize: 7.4 }, style]}>{children}</Text>
export const B = ({ children }) => <Text style={s.bold}>{children}</Text>

export function Lead({ children }) {
  return <Text style={{ fontSize: 10, color: C.text, lineHeight: 1.5, marginBottom: 10 }}>{children}</Text>
}

export function Bullets({ items, color = C.crimson }) {
  return (
    <View style={{ marginBottom: 6 }}>
      {items.map((it, i) => (
        <View key={i} wrap={false} style={[s.row, { marginBottom: 3 }]}>
          <Text style={{ width: 12, color }}>—</Text>
          <Text style={{ flex: 1 }}>{it}</Text>
        </View>
      ))}
    </View>
  )
}

export function Callout({ title, children, tone = 'crimson' }) {
  const bar = tone === 'crimson' ? C.crimson : tone === 'amber' ? '#92400E' : C.rose
  const bg = tone === 'crimson' ? C.crimsonWash : tone === 'amber' ? '#FFFBEB' : C.surface
  return (
    <View wrap={false} style={{ flexDirection: 'row', backgroundColor: bg, marginVertical: 8 }}>
      <View style={{ width: 3, backgroundColor: bar }} />
      <View style={{ flex: 1, paddingVertical: 8, paddingHorizontal: 10 }}>
        {title ? <Text style={{ fontWeight: 600, color: bar, marginBottom: 3 }}>{title}</Text> : null}
        {typeof children === 'string' ? <Text>{children}</Text> : children}
      </View>
    </View>
  )
}

