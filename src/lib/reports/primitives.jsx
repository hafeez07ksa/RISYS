/**
 * One horizontal bar split into segments. segments: [{ value, meta }].
 * Empty remainder is shown as an outlined track so "not assessed" is visible
 * rather than simply shorter.
 */
export function StackedBar({ segments, total, height = 9 }) {
  const sum = total ?? segments.reduce((a, x) => a + x.value, 0)
  return (
    <View style={[s.row, { height, backgroundColor: C.white, borderWidth: 0.6, borderColor: C.border }]}>
      {sum > 0 && segments.filter((x) => x.value > 0).map((x, i) => (
        <View key={i} style={{ width: `${(x.value / sum) * 100}%`, backgroundColor: x.meta.color }} />
      ))}
    </View>
  )
}

export function Legend({ items }) {
  return (
    <View style={[s.row, { flexWrap: 'wrap', marginTop: 3, marginBottom: 6 }]}>
      {items.map((m, i) => (
        <View key={i} style={[s.row, { alignItems: 'center', marginRight: 10, marginBottom: 2 }]}>
          <View style={{ width: 7, height: 7, backgroundColor: m.color, marginRight: 3 }} />
          <Text style={{ fontSize: 6.6, color: C.text2 }}>{m.label}</Text>
        </View>
      ))}
    </View>
  )
}

/** A two-column label / value block, for engagement and report details. */
export function FactGrid({ facts }) {
  return (
    <View style={{ marginBottom: 10 }}>
      {facts.filter(Boolean).map(([k, v], i) => (
        <View key={i} wrap={false} style={[s.row, { borderBottomWidth: 0.6, borderBottomColor: C.border3, paddingVertical: 4 }]}>
          <Text style={{ width: 120, fontSize: 7, fontWeight: 600, color: C.rose, letterSpacing: 0.6, textTransform: 'uppercase', paddingTop: 1 }}>{k}</Text>
          {typeof v === 'string' || typeof v === 'number' || v == null
            ? <Text style={{ flex: 1 }}>{v ?? '—'}</Text>
            : <View style={{ flex: 1 }}>{v}</View>}
        </View>
      ))}
    </View>
  )
}
