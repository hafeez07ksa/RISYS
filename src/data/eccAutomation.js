/** The main control a requirement id belongs to: 2-2-3-1 → 2-2-3. */
export function mainControlId(id) {
  const parts = String(id ?? '').split('-')
  return parts.length > 3 ? parts.slice(0, 3).join('-') : String(id ?? '')
}

/** Class for any ECC requirement id, subcontrols resolved through their parent. */
export function automationClassFor(id) {
  return ECC_AUTOMATION[mainControlId(id)] || null
}
